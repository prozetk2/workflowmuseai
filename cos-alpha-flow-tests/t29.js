// 1.16.0 Motion Studio → ChatGPT → Motion Studio → Flow, step by step: the AI answer is checked and asked again
// once when it misses things; each clip card shows Cắt › AI › Lời › Flow; "review first" stops after the AI step so
// the user can read / fix each clip's prompt, then "Gửi Flow" sends; the clip dialog shows the exact Flow prompt.
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const { png, check, summary } = require('./common');
const EXT = process.argv[2];
const FAKE = fs.readFileSync(__dirname + '/fake-flow-direct.html', 'utf8');
const CHAT = fs.readFileSync(__dirname + '/fake-chat.html', 'utf8');
const MP4 = fs.readFileSync(__dirname + '/v.mp4');
(async () => {
  const ctx = await chromium.launchPersistentContext('', { headless: false, viewport: { width: 1400, height: 900 }, args: [`--disable-extensions-except=${EXT}`, `--load-extension=${EXT}`, '--headless=new'] });
  const sw = ctx.serviceWorkers()[0] || await ctx.waitForEvent('serviceworker');
  const id = sw.url().split('/')[2];
  await ctx.route('https://flow.google.com/**', route => /\/media\/clip\d+\.mp4/.test(route.request().url()) ? route.fulfill({ contentType: 'video/mp4', body: MP4 }) : route.fulfill({ contentType: 'text/html', body: FAKE }));
  await ctx.route(/https:\/\/chatgpt\.com\/.*/, r => r.fulfill({ contentType: 'text/html', body: CHAT }));
  const errors = [];
  const flow = await ctx.newPage(); flow.on('pageerror', e => errors.push('flow:' + e.message));
  await flow.goto('https://flow.google.com/project/abc'); await flow.waitForTimeout(1000);
  const page = await ctx.newPage(); page.on('pageerror', e => errors.push('motion:' + e.message)); page.on('dialog', d => d.accept());
  await page.goto(`chrome-extension://${id}/motion.html`); await page.waitForTimeout(1000); await page.evaluate(() => document.querySelectorAll(".ms-side details").forEach(d => { d.open = true; }));
  const chat = await ctx.newPage(); await chat.goto('https://chatgpt.com/'); await chat.waitForTimeout(800);
  await page.evaluate(async () => { const [tab] = await chrome.tabs.query({ url: 'https://chatgpt.com/*' }); await chrome.storage.session.set({ cosalphaChatTabs: { chatgpt: tab.id } }); });
  await chat.evaluate(() => { sessionStorage.setItem('badScene', '1'); });
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'motion-'));
  const videoFile = path.join(tmp, 'source.mp4'), charFile = path.join(tmp, 'character.png');
  fs.writeFileSync(videoFile, MP4); fs.writeFileSync(charFile, png(120, 160, [200, 60, 60]));
  await page.setInputFiles('#msSourceInput', videoFile);
  await page.waitForFunction(() => window.__cosAlphaMotion?.state.project.source, null, { timeout: 20000 });
  await page.setInputFiles('#msCharInput', charFile);
  await page.waitForFunction(() => window.__cosAlphaMotion.state.project.chars.length === 1);
  await page.selectOption('#msSpeechAgent', 'chatgpt');
  await page.check('#msReview');
  await page.evaluate(() => { const s = window.__cosAlphaMotion.state.project.settings; s.clipLen = 8; s.pace = 0; s.autoFinish = false; });
  await page.click('#msSplit');
  await page.waitForFunction(() => window.__cosAlphaMotion.state.project.clips.length && !document.querySelector('#msSplit').disabled, null, { timeout: 120000 });
  check('Ô đoạn hiện các bước Cắt › AI › Lời › Flow', /Cắt›AI›Lời›Flow/.test((await page.textContent('.ms-clip .steps')).replace(/\s/g, '')));
  await page.click('#msGenerate');
  // Review stop: the AI step is done, nothing went to Flow yet, "Gửi Flow" is shown.
  await page.waitForSelector('#msContinue:not(.hidden)', { timeout: 120000 });
  const asks = await chat.evaluate(() => Number(sessionStorage.getItem('sceneAsks')));
  const scene = await page.evaluate(() => window.__cosAlphaMotion.state.project.clips[0].scene);
  console.log(asks, JSON.stringify(scene));
  check('Câu trả lời đầu thiếu (1 nhịp, không đồ vật, không góc máy) → hỏi lại ChatGPT đúng 1 lần, giữ bản đầy đủ', asks === 2 && scene.actions.length === 2 && scene.objects.length === 2 && !(scene.missing || []).length, `${asks} lần hỏi`);
  check('Câu hỏi lần 2 nói rõ chỗ thiếu', /Your previous answer for this clip had problems: there are only 1 beats/.test(await chat.evaluate(() => window.__chat.sent.at(-1))));
  check('Dừng chờ duyệt: chưa gửi gì sang Flow', (await flow.evaluate(() => window.__flowState.sent.length)) === 0);
  check('Ô đoạn: AI xong, Flow đang chờ duyệt', await page.evaluate(() => { const s = document.querySelector('.ms-clip .steps'); return /ok/.test(s.querySelectorAll('i')[1].className) && /hold/.test(s.querySelectorAll('i')[3].className); }));
  await page.click('.ms-clip');
  const preview = await page.inputValue('#msModalPrompt');
  check('Hộp thoại hiện đúng câu lệnh sẽ gửi Flow, có phần mô tả của AI', /Image 1 is the character/.test(preview) && /Action timeline, follow it beat by beat/.test(preview) && /Sound:/.test(preview), preview.slice(0, 200));
  await page.fill('#msModalScene', 'Scene (keep exactly): DA DUYET bàn trắng.'); await page.click('#msModalSaveScene');
  check('Sửa mô tả thì câu lệnh xem trước đổi theo', /DA DUYET/.test(await page.inputValue('#msModalPrompt')));
  await page.click('#msModalClose');
  await page.click('#msContinue');
  await page.waitForFunction(() => { const s = window.__cosAlphaMotion.state; return !s.running && s.project.clips.every(c => !['idle', 'running'].includes(c.status)); }, null, { timeout: 120000 });
  const sent = await flow.evaluate(() => window.__flowState.sent.map(x => x.text));
  check('Bấm Gửi Flow: gửi đúng câu lệnh đã duyệt', sent.length >= 1 && /DA DUYET/.test(sent[0]), (sent[0] || '').slice(0, 300));
  await page.waitForTimeout(800);
  const edges = await page.$$eval('.ms-clip .thumbs.edges figure', fs => fs.map(f => f.querySelector('img') ? f.textContent : ''));
  check('Ô đoạn hiện khung đầu + khung cuối của gốc và của kết quả Flow', edges.length >= 4 && edges.slice(0, 4).join('|') === 'Gốc đầu|Gốc cuối|Mới đầu|Mới cuối', JSON.stringify(edges));
  await page.click('.ms-clip');
  await page.waitForTimeout(800);
  const modalEdges = await page.$$eval('#msModalEdges figure', fs => fs.map(f => (f.querySelector('img') ? 'img:' : 'none:') + f.textContent));
  check('Hộp thoại đoạn so khung đầu / khung cuối gốc với kết quả', modalEdges.length === 4 && modalEdges.every(x => x.startsWith('img:')), JSON.stringify(modalEdges));
  await page.click('#msModalClose');
  check('Ô đoạn: Flow xong', await page.evaluate(() => /ok/.test(document.querySelectorAll('.ms-clip .steps i')[3].className)));
  check('Không có lỗi JavaScript trên trang', !errors.length, errors.join(' | '));
  const failed = summary();
  await ctx.close(); process.exit(failed ? 1 : 0);
})().catch(e => { console.error('FAIL', e); process.exit(1); });
